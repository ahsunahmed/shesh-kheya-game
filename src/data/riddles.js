function shuffle(a){ a=a.slice(); for(let i=a.length-1;i>0;i--){ const j=(Math.random()*(i+1))|0; [a[i],a[j]]=[a[j],a[i]]; } return a; }

// n-টি এলোমেলো ধাঁধা (বিকল্পও এলোমেলো)
export function pickRiddles(n){
  const pool=shuffle(RIDDLES).slice(0,n);
  return pool.map(r=>({ q:r.q, answer:r.answer, opts:shuffle(r.opts) }));
}

// ধারাবাহিকভাবে ধাঁধা জিজ্ঞাসা — সব ঠিক হলে onPass, একটা ভুল হলেই onFail(riddle)
export function askRiddles(G, riddles, titlePrefix, onPass, onFail){
  let i=0;
  const next=()=>{
    if (i>=riddles.length){ onPass(); return; }
    const r=riddles[i];
    G.ui.choice(`${titlePrefix} — ধাঁধা ${toBnLocal(i+1)}/${toBnLocal(riddles.length)}:  ${r.q}`,
      r.opts.map(o=>({id:o,label:o})),
      (ans)=>{
        if (ans===r.answer){ i++; G.ui.toast('ঠিক ধরেছ!','success',1.1); setTimeout(next,650); }
        else { onFail(r); }
      });
  };
  next();
}
function toBnLocal(n){ const B='০১২৩৪৫৬৭৮৯'; return String(n).replace(/[0-9]/g,d=>B[+d]); }
